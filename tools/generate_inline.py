#!/usr/bin/env python3
"""
Generates the arity-specific code needed for inline (suspend lambda) handlers:

- Modules/Reflection/src/main/kotlin/LambdaInvoker.kt: invokes suspend lambdas with 0..N arguments
- Modules/Functional/src/main/kotlin/InlineBuilderExtensions.kt: typed overloads get/post/... for lambdas with
  1..N parameters (arity 0 is a member of InlineBuilder so that `{ "x" }` resolves without ambiguity)
- Modules/Mcp/src/main/kotlin/ToolsHandlerBuilderExtensions.kt: typed overloads of add for tools implemented by
  lambdas with 1..N parameters (arity 0 is a member of ToolsHandlerBuilder)

Run from the repository root: python tools/generate_inline.py
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_ARITY = 16
METHODS = ["any", "get", "head", "post", "put", "delete"]

HEADER = "// Generated by tools/generate_inline.py - do not edit manually.\n\n"


def invoker():
    lines = []
    for n in range(0, MAX_ARITY + 1):
        params = ", ".join(["Any?"] * n)
        args = ", ".join([f"a[{i}]" for i in range(n)])
        lines.append(f"            {n} -> (function as suspend ({params}) -> Any?)({args})")
    body = "\n".join(lines)
    return HEADER + f'''package org.genhttp.modules.reflection

/**
 * Invokes suspend lambdas with a dynamic number of arguments.
 */
internal object LambdaInvoker {{

    /**
     * The maximum number of parameters supported for inline lambdas.
     */
    const val MaxArity: Int = {MAX_ARITY}

    @Suppress("UNCHECKED_CAST")
    suspend fun invoke(function: Function<*>, a: Array<Any?>): Any? =
        when (a.size) {{
{body}
            else -> throw IllegalArgumentException("Lambdas with more than $MaxArity parameters are not supported, use a function reference instead")
        }}

}}
'''


def extensions():
    out = [HEADER + '''@file:JvmName("InlineBuilderExtensions")

package org.genhttp.modules.functional

import org.genhttp.modules.functional.provider.InlineBuilder
''']
    for method in METHODS:
        for n in range(1, MAX_ARITY + 1):
            types = ", ".join([f"P{i}" for i in range(1, n + 1)])
            params = ", ".join([f"P{i}" for i in range(1, n + 1)])
            doc = f"Adds a {method.upper() if method != 'any' else 'request'} handler with {n} parameter{'s' if n > 1 else ''} (read from path, query, body or injected by name and type)."
            out.append(f'''
/**
 * {doc}
 */
public fun <{types}, R> InlineBuilder.{method}(function: suspend ({params}) -> R): InlineBuilder = {method}Function(null, function)

/**
 * {doc}
 *
 * @param path The path the handler is reachable at (e.g. ":id")
 */
public fun <{types}, R> InlineBuilder.{method}(path: String, function: suspend ({params}) -> R): InlineBuilder = {method}Function(path, function)
''')
    return "".join(out)


def tool_extensions():
    out = [HEADER + '''@file:JvmName("ToolsHandlerBuilderExtensions")

package org.genhttp.modules.mcp

import org.genhttp.modules.mcp.provider.ToolsHandlerBuilder
''']
    for n in range(1, MAX_ARITY + 1):
        types = ", ".join([f"P{i}" for i in range(1, n + 1)])
        out.append(f'''
/**
 * Adds a tool with {n} argument{'s' if n > 1 else ''} implemented by the given lambda (parameters are read from the arguments sent by
 * the client or injected by the framework by their type).
 *
 * @param name The name of the tool
 * @param description Describes the purpose of the tool to the model
 * @param function The lambda implementing the tool (a suspend lambda with explicitly typed parameters)
 */
public fun <{types}, R> ToolsHandlerBuilder.add(name: String, description: String, function: suspend ({types}) -> R): ToolsHandlerBuilder =
    addFunction(name, description, function)
''')
    return "".join(out)


def write(path, content):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print("written", path)


if __name__ == "__main__":
    write("Modules/Reflection/src/main/kotlin/LambdaInvoker.kt", invoker())
    write("Modules/Functional/src/main/kotlin/InlineBuilderExtensions.kt", extensions())
    write("Modules/Mcp/src/main/kotlin/ToolsHandlerBuilderExtensions.kt", tool_extensions())
