package org.genhttp.modules.reflection

import org.genhttp.api.content.Handler
import org.genhttp.api.infrastructure.Server
import org.genhttp.api.protocol.ByteString
import org.genhttp.api.protocol.KnownHeaders
import org.genhttp.api.protocol.Request
import org.genhttp.api.protocol.Response
import org.genhttp.api.protocol.getEntry
import org.genhttp.api.protocol.preAllocate
import org.genhttp.modules.reflection.operations.ArgumentProvider
import org.genhttp.modules.reflection.operations.Operation
import org.genhttp.modules.reflection.operations.OperationArgumentSource
import org.genhttp.modules.reflection.operations.SignatureAnalyzer
import org.genhttp.modules.reflection.routing.RoutingMatch

import java.lang.reflect.InvocationTargetException

import kotlin.reflect.KClass
import kotlin.reflect.KParameter
import kotlin.reflect.full.callSuspend
import kotlin.reflect.full.callSuspendBy
import kotlin.reflect.jvm.isAccessible

/**
 * Checks whether the request should be handled by an interceptor instead of the operation.
 */
public fun interface RequestInterception {

    /**
     * Invokes the interceptors of the operation.
     *
     * @return The response generated by an interceptor or null, if the operation should be invoked
     */
    public suspend fun intercept(request: Request, arguments: Map<ByteString, Any?>, acceptedFormat: ByteString?): Response?

}

/**
 * Executes a single operation of a service.
 *
 * @property operation The operation to be executed
 * @property registry The registries used to read arguments and to write results
 * @param instanceProvider Provides the instance the function is invoked on (ignored for inline lambdas)
 */
public class MethodHandler(
    public val operation: Operation,
    private val instanceProvider: suspend (Request) -> Any,
    public val registry: MethodRegistry
) : Handler {

    private val responseProvider = ResponseProvider(registry)

    private val interceptor = RequestInterception { request, arguments, acceptedFormat -> intercept(request, arguments, acceptedFormat) }

    private val parameters: List<KParameter> = SignatureAnalyzer.valueParameters(operation.method)

    private val instanceParameter: KParameter? = operation.method.parameters.firstOrNull { it.kind == KParameter.Kind.INSTANCE }

    private val useReflection: Boolean = (operation.executionSettings.mode ?: ExecutionMode.Auto) == ExecutionMode.Reflection

    init {
        if (operation.delegate == null) {
            runCatching { operation.method.isAccessible = true }
        }
    }

    // region Functionality

    override suspend fun prepare(server: Server) {
        // nothing to prepare, signatures have been analyzed when creating the operation
    }

    override suspend fun handle(request: Request): Response? = handle(request, RoutingMatch(0, null))

    /**
     * Handles the given request that matched the route of the operation.
     */
    public suspend fun handle(request: Request, match: RoutingMatch): Response? {
        if (match.offset > 0) {
            request.header.target.advance(match.offset)
        }

        val accepted = request.header.headers.getEntry(KnownHeaders.Accept).preAllocate(request)

        val arguments = getArguments(request, match)

        val interception = interceptor.intercept(request, arguments.named, accepted)

        if (interception != null) {
            return interception
        }

        val result = invoke(request, arguments)

        return responseProvider.getResponse(request, operation, result, accepted)
    }

    private suspend fun getArguments(request: Request, match: RoutingMatch): Arguments {
        if (parameters.isEmpty()) {
            return Arguments.None
        }

        val named = LinkedHashMap<ByteString, Any?>(parameters.size)
        val values = arrayOfNulls<Any?>(parameters.size)
        val omitted = BooleanArray(parameters.size)

        for ((index, parameter) in parameters.withIndex()) {
            val name = parameter.name ?: continue
            val argument = operation.arguments[name] ?: continue

            val value = when (argument.source) {
                OperationArgumentSource.Injected -> ArgumentProvider.getInjectedArgument(request, this, argument, registry)
                OperationArgumentSource.Path -> ArgumentProvider.getPathArgument(argument.name, argument.type, match, registry)
                OperationArgumentSource.Body -> ArgumentProvider.getBodyArgument(request, argument.name, argument.type, registry)
                OperationArgumentSource.Query -> ArgumentProvider.getQueryArgument(request, argument, registry)
                OperationArgumentSource.Content -> ArgumentProvider.getContent(request, argument, registry)
                OperationArgumentSource.Streamed -> ArgumentProvider.getStream(request)
            }

            if (value == null && argument.isOptional) {
                // let the declared default value apply
                omitted[index] = true
            }

            val effective = value ?: if (argument.isOptional) null else defaultOf(argument.type.classifier, argument.type.isMarkedNullable)

            values[index] = effective
            named[argument.name] = effective
        }

        return Arguments(named, values, omitted)
    }

    private suspend fun intercept(request: Request, arguments: Map<ByteString, Any?>, acceptedFormat: ByteString?): Response? {
        for (interceptor in operation.interceptors) {
            val result = interceptor.intercept(request, operation, arguments)

            if (result != null) {
                return responseProvider.getResponse(request, operation, result.payload, acceptedFormat) { result.apply(this) }
            }
        }

        return null
    }

    private suspend fun invoke(request: Request, arguments: Arguments): Any? {
        try {
            val delegate = operation.delegate

            if (delegate != null) {
                return LambdaInvoker.invoke(delegate, arguments.values)
            }

            val function = operation.method
            val instance = if (instanceParameter != null) instanceProvider(request) else null

            if (!useReflection && !arguments.hasOmitted) {
                return if (instanceParameter != null) {
                    function.callSuspend(instance, *arguments.values)
                } else {
                    function.callSuspend(*arguments.values)
                }
            }

            val map = HashMap<KParameter, Any?>(parameters.size + 1)

            if (instanceParameter != null) {
                map[instanceParameter] = instance
            }

            for ((index, parameter) in parameters.withIndex()) {
                if (!arguments.omitted[index]) {
                    map[parameter] = arguments.values[index]
                }
            }

            return function.callSuspendBy(map)
        } catch (e: InvocationTargetException) {
            throw e.targetException ?: e
        }
    }

    // endregion

    private class Arguments(val named: Map<ByteString, Any?>, val values: Array<Any?>, val omitted: BooleanArray) {

        val hasOmitted: Boolean = omitted.any { it }

        companion object {
            val None = Arguments(emptyMap(), emptyArray(), BooleanArray(0))
        }

    }

    private companion object {

        /**
         * The value passed for a missing, required argument (`null` for reference types, zero for primitives,
         * like .NET passes `default(T)`).
         */
        fun defaultOf(classifier: Any?, nullable: Boolean): Any? {
            if (nullable || classifier !is KClass<*>) {
                return null
            }

            return when (classifier) {
                Int::class -> 0
                Long::class -> 0L
                Short::class -> 0.toShort()
                Byte::class -> 0.toByte()
                Double::class -> 0.0
                Float::class -> 0f
                Boolean::class -> false
                Char::class -> '\u0000'
                else -> null
            }
        }
    }

}
