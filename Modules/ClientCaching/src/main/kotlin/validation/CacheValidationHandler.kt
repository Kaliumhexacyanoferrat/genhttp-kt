package org.genhttp.modules.clientcaching.validation

import org.genhttp.api.content.Handler
import org.genhttp.api.content.services.ApiRequestHeader
import org.genhttp.api.content.services.ApiResponse
import org.genhttp.api.content.services.ApiResponseHeader
import org.genhttp.api.content.services.DocumentedConcern
import org.genhttp.api.content.services.OperationDocumentation
import org.genhttp.api.infrastructure.Server
import org.genhttp.api.protocol.ByteString
import org.genhttp.api.protocol.Connection
import org.genhttp.api.protocol.KnownHeaders
import org.genhttp.api.protocol.Request
import org.genhttp.api.protocol.RequestMethod
import org.genhttp.api.protocol.Response
import org.genhttp.api.protocol.ResponseStatus
import org.genhttp.api.protocol.getEntry
import org.genhttp.api.protocol.preAllocate
import org.genhttp.modules.io.hasType

/**
 * Tags the content generated by the handler it wraps with an ETag and answers requests
 * for unchanged content with a `304 Not Modified` response.
 *
 * @param content The handler to be wrapped by this concern
 */
public class CacheValidationHandler(override val content: Handler) : DocumentedConcern {

    // region Functionality

    override suspend fun handle(request: Request): Response? {
        val isSupported = request.hasType(*SupportedMethods)

        val cached = request.header.headers.getEntry(KnownHeaders.IfNoneMatch).preAllocate(request)

        val response = content.handle(request)

        if (response != null && isSupported) {
            if (response.content != null && response.mode != Connection.Upgrade) {
                val existing = response.headers.getEntry(KnownHeaders.ETag)

                val eTag = existing ?: calculateETag(response)

                val builder = response.rebuild()

                if (cached != null && eTag != null) {
                    if (cached == eTag) {
                        builder.status(ResponseStatus.NotModified)
                        builder.content(null)
                    }
                }

                if (existing == null && eTag != null) {
                    builder.header(KnownHeaders.ETag, eTag)
                }
            }
        }

        return response
    }

    override suspend fun prepare(server: Server) {
        content.prepare(server)
    }

    override fun addDocumentation(operation: OperationDocumentation) {
        if (operation.method == RequestMethod.Get || operation.method == RequestMethod.Head) {
            operation.add(ApiRequestHeader(name = "If-None-Match", description = "The ETag of a previously received response, to check whether the content has changed since"))
                .add(ApiResponse(status = ResponseStatus.NotModified, description = "The content has not changed since it has been received with the given ETag"))
                .add(ApiResponseHeader(name = "ETag", description = "Identifies the version of the returned content", status = arrayOf(ResponseStatus.Ok)))
                .add(ApiResponseHeader(name = "ETag", description = "Identifies the version of the content", status = arrayOf(ResponseStatus.NotModified)))
        }
    }

    private suspend fun calculateETag(response: Response): ByteString? {
        val body = response.content

        if (body != null) {
            val checksum = body.calculateChecksum()

            if (checksum != null) {
                // the checksum is an unsigned 64 bit value in GenHTTP
                return ByteString("\"${java.lang.Long.toUnsignedString(checksum)}\"")
            }
        }

        return null
    }

    // endregion

    private companion object {

        private val SupportedMethods: Array<RequestMethod> = arrayOf(RequestMethod.Get, RequestMethod.Head)

    }

}
