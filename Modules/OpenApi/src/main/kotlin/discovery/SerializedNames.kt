package org.genhttp.modules.openapi.discovery

import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.databind.PropertyNamingStrategy
import com.fasterxml.jackson.databind.cfg.MapperConfig
import com.fasterxml.jackson.databind.introspect.AnnotatedField
import com.fasterxml.jackson.databind.introspect.AnnotatedMember
import com.fasterxml.jackson.databind.introspect.AnnotatedMethod
import com.fasterxml.jackson.databind.introspect.AnnotatedParameter

import io.swagger.v3.core.util.Json

import tools.jackson.databind.json.JsonMapper

import java.lang.reflect.Member
import java.util.concurrent.ConcurrentHashMap

/**
 * Provides the names of the properties written by a JSON mapper of the Conversion module,
 * so the generated schemas match the wire format (System.Text.Json reflection service of NJsonSchema upstream).
 *
 * The schemas are generated by swagger-core, which analyzes types with its own (Jackson 2) mapper.
 * [createSchemaMapper] creates such a mapper that names the properties like the given (Jackson 3) mapper
 * does (e.g. following its naming strategy), [isWritten] tells whether a property is written at all.
 */
internal class SerializedNames(private val mapper: JsonMapper) {

    private val cache = ConcurrentHashMap<Class<*>, SerializedProperties>()

    /**
     * The properties written for instances of the given class.
     */
    fun of(type: Class<*>): SerializedProperties = cache.computeIfAbsent(type, ::introspect)

    /**
     * The name the given member of the class is written with, if it is written at all.
     */
    fun find(type: Class<*>, member: Member?): String? = member?.let { of(type).names[it] }

    /**
     * Creates the mapper swagger-core analyzes types with, which names their properties like the mapper of the format.
     */
    fun createSchemaMapper(): ObjectMapper = Json.mapper().copy().setPropertyNamingStrategy(Naming())

    private fun introspect(type: Class<*>): SerializedProperties {
        val names = HashMap<Member, String>()
        val written = LinkedHashSet<String>()

        runCatching {
            val description = mapper._serializationContext().introspectBeanDescription(mapper.constructType(type))

            for (property in description.findProperties()) {
                if (!property.couldSerialize()) {
                    continue
                }

                written.add(property.name)

                for (member in listOfNotNull(property.getter, property.field, property.setter)) {
                    member.member?.let { names.putIfAbsent(it, property.name) }
                }
            }
        }

        return SerializedProperties(names, written)
    }

    /**
     * Renames the properties found by swagger-core like the mapper of the format names them. Explicitly named
     * properties are kept as they are, as both mappers apply naming strategies to implicit names only.
     */
    private inner class Naming : PropertyNamingStrategy() {

        override fun nameForField(config: MapperConfig<*>, field: AnnotatedField, defaultName: String): String =
            rename(field, defaultName)

        override fun nameForGetterMethod(config: MapperConfig<*>, method: AnnotatedMethod, defaultName: String): String =
            rename(method, defaultName)

        override fun nameForSetterMethod(config: MapperConfig<*>, method: AnnotatedMethod, defaultName: String): String =
            rename(method, defaultName)

        override fun nameForConstructorParameter(config: MapperConfig<*>, ctorParam: AnnotatedParameter, defaultName: String): String =
            defaultName

        private fun rename(member: AnnotatedMember, defaultName: String): String =
            find(member.declaringClass, member.member) ?: defaultName

    }

}

/**
 * The properties written by a mapper for instances of a class.
 *
 * @property names The names of the written properties, keyed by the members they are read from or written to
 * @property written The names of all written properties (empty, if the class is not written as an object with properties)
 */
internal class SerializedProperties(val names: Map<Member, String>, val written: Set<String>) {

    /**
     * Whether the property with the given name is written by the mapper. If the mapper does not
     * write the class as an object with properties, all properties are considered to be written.
     */
    fun isWritten(name: String): Boolean = written.isEmpty() || name in written

}
