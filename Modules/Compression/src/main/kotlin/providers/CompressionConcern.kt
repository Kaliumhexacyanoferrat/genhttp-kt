package org.genhttp.modules.compression.providers

import org.genhttp.api.content.Concern
import org.genhttp.api.content.Handler
import org.genhttp.api.content.io.CompressionAlgorithm
import org.genhttp.api.content.io.CompressionLevel
import org.genhttp.api.infrastructure.Server
import org.genhttp.api.protocol.ByteString
import org.genhttp.api.protocol.Connection
import org.genhttp.api.protocol.ContentType
import org.genhttp.api.protocol.KnownHeaders
import org.genhttp.api.protocol.Request
import org.genhttp.api.protocol.Response
import org.genhttp.api.protocol.getEntry
import org.genhttp.api.protocol.preAllocate

/**
 * Compresses the content generated by the wrapped handler, if the client supports one of the configured
 * algorithms and the content is of a type that benefits from compression.
 *
 * @param content The handler to be wrapped by this concern
 * @param algorithms The algorithms that can be used to compress the content (the one with the highest priority
 * supported by the client will be selected)
 * @param level The level of compression to be applied
 * @param minimumSize The minimum size of the content (in bytes) required to compress it, if its length is known
 * (null, to compress content of any size)
 */
public class CompressionConcern(
    override val content: Handler,
    algorithms: List<CompressionAlgorithm>,
    private val level: CompressionLevel,
    private val minimumSize: Long?
) : Concern {

    private val algorithms: List<CompressionAlgorithm> = algorithms.sortedByDescending { it.priority }

    override suspend fun handle(request: Request): Response? {
        val acceptEncoding = request.header.headers.getEntry(KnownHeaders.AcceptEncoding).preAllocate(request)

        val response = content.handle(request) ?: return null

        val responseContent = response.content

        if (responseContent != null && responseContent.encoding == null && response.mode != Connection.Upgrade) {
            if (shouldCompressByType(responseContent.type) && shouldCompressBySize(response)) {
                if (acceptEncoding != null) {
                    for (algorithm in algorithms) {
                        if (!AcceptEncodingHeader.isSupported(acceptEncoding, algorithm.name)) {
                            continue
                        }

                        val builder = response.rebuild()

                        builder.content(algorithm.compress(responseContent, level))

                        val vary = response.headers.getEntry(KnownHeaders.Vary)

                        if (vary != null) {
                            val varyBytes = vary.bytes
                            val acceptEncodingBytes = KnownHeaders.AcceptEncoding.bytes

                            val combined = ByteArray(varyBytes.remaining() + acceptEncodingBytes.remaining() + 2)

                            var offset = 0

                            varyBytes.get(varyBytes.position(), combined, offset, varyBytes.remaining())
                            offset += varyBytes.remaining()

                            combined[offset++] = ','.code.toByte()
                            combined[offset++] = ' '.code.toByte()

                            acceptEncodingBytes.get(acceptEncodingBytes.position(), combined, offset, acceptEncodingBytes.remaining())

                            builder.header(KnownHeaders.Vary, ByteString(combined))
                        } else {
                            builder.header(KnownHeaders.Vary, KnownHeaders.AcceptEncoding)
                        }

                        return builder.build()
                    }
                }
            }
        }

        return response
    }

    private fun shouldCompressByType(type: ContentType?): Boolean {
        if (type != null) {
            val withoutOptions = type.withoutOptions()

            if (CompressibleTypes.contains(withoutOptions)) {
                return true
            }
        }

        return false
    }

    private fun shouldCompressBySize(response: Response): Boolean {
        val contentLength = response.content?.length

        return minimumSize == null || contentLength == null || contentLength >= minimumSize
    }

    override suspend fun prepare(server: Server) {
        content.prepare(server)
    }

    private companion object {

        @Suppress("DEPRECATION")
        private val CompressibleTypes: Set<ContentType> = hashSetOf(
            ContentType.ApplicationJavaScript,
            ContentType.ApplicationJson,
            ContentType.AudioWav,
            ContentType.TextCss,
            ContentType.TextCsv,
            ContentType.TextHtml,
            ContentType.TextPlain,
            ContentType.TextRichText,
            ContentType.ApplicationRtf,
            ContentType.FontWoff,
            ContentType.FontTrueTypeFont,
            ContentType.FontOpenTypeFont,
            ContentType.FontEmbeddedOpenTypeFont,
            ContentType.ImageScalableVectorGraphics,
            ContentType.ImageScalableVectorGraphicsXml,
            ContentType.ImageBmp,
            ContentType.TextXml,
            ContentType.TextJavaScript,
            ContentType.ApplicationYaml
        )

    }

}
